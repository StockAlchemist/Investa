"""
Qt-free presentation defaults shared by the GUI and the web/API backend.

This module deliberately has no GUI (PySide6) dependency so that server-side
code (e.g. config_manager) can import column definitions and graph date
defaults without pulling in Qt. GUI-only helpers and QColor constants live in
utils.py, which re-exports the names defined here for backwards compatibility.
"""

from datetime import date, timedelta
from typing import Tuple

from config import DEFAULT_GRAPH_DAYS_AGO
from utils_time import get_est_today


# --- Graph Defaults ---
def default_graph_dates() -> Tuple[date, date]:
    """The default graph window, ending on the market's day.

    A function, not import-time constants: those read the server's date (a day
    ahead of New York on the Bangkok host) and then stayed fixed for the life of
    the process (fixed 9 Nov 2026).
    """
    end = get_est_today()
    return end - timedelta(days=DEFAULT_GRAPH_DAYS_AGO), end


